def format_roadmap_markdown(persona, recommendation, roadmap):
    """Format a complete multi-step roadmap into an academic Markdown document."""
    cr = roadmap["course_roadmap"]
    gaps = roadmap["gaps"]
    projects = roadmap["projects"]
    milestones = roadmap["career_milestones"]
    education = roadmap["education_guidance"]

    md = []
    md.append(f"# CareerCompass Roadmap: {roadmap['title']}")
    md.append(f"**Deliverable Type:** Sample Generated Career & Education Roadmap  ")
    md.append(f"**Target Persona:** {persona['student_name']} — {persona['background']}  ")
    md.append(f"**O*NET-SOC Code:** `{roadmap['code']}` | **Job Zone:** `{roadmap['job_zone']}` | **Random Forest Predicted Zone:** `{roadmap.get('predicted_job_zone', 'N/A')}`  ")
    md.append(f"**Profile Match Score:** `{recommendation['Match Score (%)']:.2f}%` (Interest: `{recommendation['Interest Match (%)']:.1f}%`, Skill: `{recommendation['Skill Match (%)']:.1f}%`)  \n")
    md.append("---\n")

    md.append("## 1. Executive Summary & Occupation Overview")
    md.append(f"> {roadmap.get('description', 'Comprehensive career profile generated by CareerCompass.')}\n")
    md.append("### Student Assessment Input")
    md.append("- **Student Interest Profile Ratings (0-5):**")
    for int_name, val in persona["interests"].items():
        md.append(f"  - `{int_name.title()}`: {val}/5.0")
    md.append("- **Initial Self-Reported Skills (0-5):**")
    for skl_name, val in persona["skills"].items():
        md.append(f"  - `{skl_name}`: {val}/5.0")
    md.append("\n---\n")

    md.append("## 2. Step 1: Coursework Roadmap (Courses)")
    md.append("The coursework plan bridges the student's foundation to advanced occupational requirements across three academic stages.\n")

    md.append("### Stage 1: Foundational Prerequisites (Semesters 1–2)")
    for c in cr["stage_1_foundational"]:
        md.append(f"- **{c}**")

    md.append("\n### Stage 2: Core & Major Discipline (Semesters 3–4)")
    for c in cr["stage_2_core"]:
        md.append(f"- **{c}**")

    if cr.get("stage_3_advanced"):
        md.append("\n### Stage 3: Advanced Specialization & Capstone (Semesters 5+)")
        for c in cr["stage_3_advanced"]:
            md.append(f"- **{c}**")

    if cr.get("certifications"):
        md.append("\n### Recommended Industry Credentials & Certifications")
        for cert in cr["certifications"]:
            md.append(f"- 🏆 **{cert}**")

    md.append("\n---\n")

    md.append("## 3. Step 2: Skill Acquisition & Gap Remediation (Skills)")
    md.append("Priority gaps calculated against official O*NET benchmark requirements for this occupation:\n")
    if gaps:
        md.append("| Essential Skill | Current Level | O*NET Target | Skill Gap | Priority Actionable Exercise |")
        md.append("| :--- | :---: | :---: | :---: | :--- |")
        for g in gaps:
            md.append(
                f"| **{g['skill']}** | `{g['current']:.1f}/5.0` | `{g['importance']:.2f}/5.0` | **+{g['gap']:.2f}** | {g['actionable_exercise']} |"
            )
    else:
        md.append("No critical skill deficiencies detected; continue maintaining advanced proficiencies.")

    md.append("\n### High-Impact O*NET Knowledge Domains:")
    for ka in roadmap["knowledge_areas"]:
        md.append(f"- **{ka['name']}** (O*NET Importance Rating: `{ka['importance']:.2f}/5.0`)")

    md.append("\n---\n")

    md.append("## 4. Step 3: Practical Portfolio Projects (Artifacts)")
    md.append("Hands-on proof-of-work required to demonstrate applied competence to recruiters and academic admissions:\n")
    for i, p in enumerate(projects, 1):
        md.append(f"{i}. **{p}**")

    md.append("\n---\n")

    md.append("## 5. Step 4: Career Entry Milestones & Job Zone Preparation (Career)")
    md.append("### Degree & Education Requirements")
    for item in education:
        md.append(f"- {item}")

    md.append("\n### Chronological Roadmap Milestones")
    for m in milestones:
        md.append(f"- 📌 **{m}**")

    md.append("\n---\n")
    md.append("*Generated by CareerCompass AI Advisor — Supervised Learning Course Project (CSE395)*\n")

    return "\n".join(md)


def generate_all():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    profiles = load_profiles()

    index_summary = [
        "# CareerCompass: Sample Generated Roadmaps Index",
        "This directory contains the **3 sample generated roadmaps** required as primary deliverables for the CareerCompass project.\n",
        "Each roadmap proves the personalized **(Courses → Skills → Career)** multi-step agent planning process on diverse student personas:\n",
        "| Sample | Student Persona | Domain / Focus | Target O*NET Occupation | O*NET Job Zone | Supervised ML Predicted Zone | Document Link |",
        "| :---: | :--- | :--- | :--- | :---: | :---: | :--- |",
    ]

    for persona in SAMPLE_PERSONAS:
        print(f"\nProcessing Persona {persona['id']}: {persona['student_name']}...")
        recs = recommend_careers(persona["interests"], persona["skills"], top_n=10)

        # Look for target override or top match
        match = recs[recs["Title"] == persona["target_override_title"]]
        if not match.empty:
            chosen = match.iloc[0]
        else:
            chosen = recs.iloc[0]

        occ = find_occupation(profiles, occupation_code=chosen["O*NET-SOC Code"])
        roadmap = generate_roadmap(occ, persona["skills"], predicted_job_zone=chosen.get("Predicted Job Zone"))

        md_content = format_roadmap_markdown(persona, chosen, roadmap)
        out_file = OUTPUT_DIR / persona["filename"]
        out_file.write_text(md_content, encoding="utf-8")
        print(f"  -> Saved {out_file.name}")

        index_summary.append(
            f"| **{persona['id']}** | **{persona['student_name']}** | {persona['background']} | **{roadmap['title']}** (`{roadmap['code']}`) | `{roadmap['job_zone']}` | `{roadmap.get('predicted_job_zone')}` | [`{persona['filename']}`](./{persona['filename']}) |"
        )

    index_summary.append("\n---\n")
    index_summary.append("### Pipeline Verification Notes:")
    index_summary.append("- **Supervised Learning Integration:** Job Zone is predicted by the Random Forest Classifier trained on 49 occupational features, verifying the required preparation level for each career pathway.")
    index_summary.append("- **Pathway Completeness:** Every sample demonstrates specific Coursework stages, quantified Skill gaps with remedial exercises, portfolio Projects, and long-term Career milestones.")

    (OUTPUT_DIR / "README.md").write_text("\n".join(index_summary), encoding="utf-8")
    print(f"  -> Saved {OUTPUT_DIR / 'README.md'}")
    print("\nAll 3 sample generated roadmaps have been successfully produced!")


if __name__ == "__main__":
    generate_all()
